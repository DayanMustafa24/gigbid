"""Parse the Kaggle Upwork jobs CSV into clean records + aggregated price statistics.

Run: uv run python -m scripts.parse_upwork
Outputs: data/processed/jobs_real.jsonl   (git-ignored, regenerated by `make seed`)
         data/reference/price_stats.json  (small aggregate, committed)
Real data: Kaggle "upwork-job-postings-dataset-2024-50k-records" (asaniczka). See docs/DATA_CARD.md.
"""
from __future__ import annotations

import hashlib
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

_COUNTRY_TAIL = re.compile(r"Country:\s*(?P<c>.*?)(?:click to apply)?\s*$", re.S)

PERSONA_RULES: list[tuple[str, tuple[str, ...]]] = [
    ("ai_ml", ("machine learning", "deep learning", "nlp", "natural language", "tensorflow", "pytorch", "llm",
               "openai", "chatgpt", "computer vision", "data science", "artificial intelligence", "chatbot",
               "scikit", "langchain", "hugging face", "neural network", "generative ai", "ai")),
    ("data_analyst", ("data analysis", "data analytics", "power bi", "tableau", "looker", "sql", "excel",
                      "data visualization", "dashboard", "business intelligence", "google analytics", "statistics",
                      "etl", "data mining")),
    ("fullstack_web", ("react", "node.js", "javascript", "typescript", "django", "next.js", "vue", "angular",
                       "full stack", "web development", "api", "laravel", "php", "wordpress", "front-end",
                       "back-end", "html", "css", "web application", "flask", "fastapi", "postgresql")),
]


def job_id_from_link(link: str) -> str:
    m = re.search(r"(?:%7E|~)([0-9a-f]{10,})", link or "", re.I)
    return m.group(1) if m else hashlib.sha1((link or "").encode()).hexdigest()[:18]


def parse_description(raw: str) -> dict:
    """Split the scraped description blob into body / budget / category / skills / country."""
    text = html.unescape(raw or "")
    country_tail = None
    mc = _COUNTRY_TAIL.search(text)
    if mc and "Skills:" in text[: mc.start()]:
        country_tail = mc.group("c").strip() or None
        text = text[: mc.start()]
    text = re.sub(r"click to apply\s*$", "", text.strip())
    # anchor on the LAST "Posted On:" so job text containing "Budget:" is not confused for metadata
    idx = text.rfind("Posted On:")
    out = {"body": text.strip(), "budget_text": None, "category": None, "skills": [], "country_text": country_tail}
    if idx == -1:
        return out
    head = text[:idx]
    meta = text[idx:]
    mb = re.search(r"(Budget|Hourly Range):\s*([^A-Za-z]*)$", head)
    if mb:
        out["budget_text"] = f"{mb.group(1)}: {mb.group(2).strip()}"
        head = head[: mb.start()]
    out["body"] = head.strip()
    mc2 = re.search(r"Category:\s*(.*?)Skills:", meta, re.S)
    if mc2:
        out["category"] = mc2.group(1).strip() or None
    ms = re.search(r"Skills:(.*?)(?:Skills:|$)", meta[meta.find("Skills:"):], re.S) if "Skills:" in meta else None
    if ms:
        seen, skills = set(), []
        for s in ms.group(1).split(","):
            s = re.sub(r"\s+", " ", s).strip()
            if s and s.lower() not in seen:
                seen.add(s.lower())
                skills.append(s)
        out["skills"] = skills
    return out


def persona_domain(category: str | None, skills: list[str], title: str = "") -> str:
    hay = " ".join([category or "", title, *skills]).lower()
    for persona, keys in PERSONA_RULES:
        if any(re.search(r"(?<![a-z])" + re.escape(k) + r"(?![a-z])", hay) for k in keys):
            return persona
    return "other"


def dup_key(title: str, body: str) -> str:
    norm = re.sub(r"\W+", " ", (title + " " + body[:200]).lower()).strip()
    return hashlib.sha1(norm.encode()).hexdigest()[:16]


def main() -> None:
    import pandas as pd

    src = sorted((ROOT / "data" / "external").rglob("upwork-jobs*.csv"))
    if not src:
        raise SystemExit("No upwork-jobs*.csv under data/external/")
    df = pd.read_csv(src[0], sep=None, engine="python")
    out_dir = ROOT / "data" / "processed"
    ref_dir = ROOT / "data" / "reference"
    out_dir.mkdir(parents=True, exist_ok=True)
    ref_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    for r in df.itertuples(index=False):
        p = parse_description(r.description if isinstance(r.description, str) else "")
        title = str(r.title or "").strip()
        rows.append({
            "job_id": job_id_from_link(str(r.link)),
            "title": title,
            "body": p["body"],
            "category": p["category"],
            "skills": p["skills"],
            "is_hourly": str(r.is_hourly).upper() == "TRUE",
            "hourly_low": None if pd.isna(r.hourly_low) else float(r.hourly_low),
            "hourly_high": None if pd.isna(r.hourly_high) else float(r.hourly_high),
            "budget": None if pd.isna(r.budget) else float(r.budget),
            "country": p["country_text"] or (None if pd.isna(r.country) else str(r.country)),
            "posted": str(r.published_date),
            "persona_domain": persona_domain(p["category"], p["skills"], title),
            "dup_key": dup_key(title, p["body"]),
            "source": "kaggle:asaniczka/upwork-job-postings-dataset-2024-50k-records",
            "synthetic": False,
        })
    with open(out_dir / "jobs_real.jsonl", "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    jobs = pd.DataFrame(rows)
    jobs["near_dup"] = jobs.duplicated("dup_key", keep="first")

    def q(s: pd.Series, x: float):
        return None if s.empty else round(float(s.quantile(x)), 2)

    def stats(g: pd.DataFrame) -> dict:
        fixed = g.loc[(~g.is_hourly) & (g.budget > 0), "budget"]
        hl = g.loc[g.is_hourly & (g.hourly_low > 0), "hourly_low"]
        hh = g.loc[g.is_hourly & (g.hourly_high > 0), "hourly_high"]
        return {
            "n": int(len(g)), "n_fixed": int(len(fixed)), "n_hourly": int(len(hl)),
            "fixed_p25": q(fixed, .25), "fixed_median": q(fixed, .5), "fixed_p75": q(fixed, .75),
            "hourly_low_median": q(hl, .5), "hourly_high_median": q(hh, .5),
            "hourly_p25": q(hl, .25), "hourly_p75": q(hh, .75),
        }

    price = {
        "source": "kaggle:asaniczka/upwork-job-postings-dataset-2024-50k-records (Dec 2023 - Feb 2024)",
        "rows": int(len(jobs)),
        "near_duplicate_rows": int(jobs.near_dup.sum()),
        "overall": stats(jobs),
        "by_persona_domain": {k: stats(g) for k, g in jobs.groupby("persona_domain")},
        "by_category": {k: stats(g) for k, g in jobs.groupby("category") if len(g) >= 20},
    }
    (ref_dir / "price_stats.json").write_text(json.dumps(price, indent=2), encoding="utf-8")
    print(json.dumps({"rows": price["rows"], "near_dups": price["near_duplicate_rows"],
                      "persona_counts": jobs.persona_domain.value_counts().to_dict(),
                      "categories_with_stats": len(price["by_category"])}, indent=2))


if __name__ == "__main__":
    main()
