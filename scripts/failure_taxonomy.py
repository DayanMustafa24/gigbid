"""Failure taxonomy (assignment R&D report): every wrong or failed job of the shipped graph, grouped by cause.

    uv run python -m scripts.failure_taxonomy        # reads evals/results/{ci_smoke,rdc_architectures,x2_experiment}.json, writes docs/FAILURE_TAXONOMY.md

Only the hand-built graph is analysed (the product). Gold reasons come from the dev sets (known by construction). Nothing is invented: a
failure appears only if a results file contains it. Categories are assigned by rule from the gold label and the direction of the error.
"""
from __future__ import annotations

import json
from collections import Counter
from typing import Any

from agent.settings import ROOT
from evals.runners.rag_eval import PERSONAS, RESULTS, load_dev

OUT = ROOT / "docs" / "FAILURE_TAXONOMY.md"


def category(gold: dict[str, Any], pred: str | None) -> str:
    if pred is None:
        return "no decision (error, budget or dead letter)"
    if pred == "bid":  # gold was skip: a false bid
        if gold.get("scam"):
            return "false bid on a scam"
        if gold.get("duplicate_of"):
            return "false bid on a duplicate/repost"
        if gold.get("injection"):
            return "false bid on an injected job"
        return "false bid on an unfit or low-budget job"
    if gold.get("injection"):
        return "missed bid: injected but legitimate job skipped"
    return "missed bid: a fit job was skipped"


def load(name: str) -> Any:
    p = RESULTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def main() -> int:
    jobs = {(p, j["job_id"]): j for p in PERSONAS for j in load_dev(p)}
    by_id: dict[str, list[str]] = {}
    for p, jid in jobs:
        by_id.setdefault(jid, []).append(p)
    found: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()
    ambiguous = 0

    def add(src: str, job_id: str, pred: str | None, persona: str | None = None, note: str = "") -> None:
        nonlocal ambiguous
        if persona is None and len(by_id.get(job_id, [])) == 1:
            persona = by_id[job_id][0]
        if (persona, job_id) not in jobs:
            ambiguous += 1  # id shared by several personas and the old result row has no persona: cannot be joined safely
            return
        if (src, f"{persona}/{job_id}") in seen:
            return
        seen.add((src, f"{persona}/{job_id}"))
        g = jobs[(persona, job_id)]["gold"]
        found.append({"source": src, "job_id": f"{persona}/{job_id}", "gold": g["action"], "pred": pred, "reason": g.get("reason", ""),
                      "category": category(g, pred), "note": note})

    smoke = load("ci_smoke.json")
    for r in (smoke or {}).get("rows", []):
        if r["pred"] != r["gold"]:
            add("ci_smoke (30 jobs)", r["job_id"], r["pred"], r.get("persona"))
    rdc = load("rdc_architectures.json")
    for r in ((rdc or {}).get("rows") or {}).get("hand_graph", []):
        if r["pred"] != r["gold"]:
            add("rdc hand_graph (48 jobs)", r["job_id"], r["pred"], r.get("persona"))
    x2 = load("x2_experiment.json")
    for r in (x2 or {}).get("rows", []):
        if "skipped" in r or "error" in r:
            add("x2 (bid-gold jobs not drafted)", r["job_id"], None if "error" in r else "skip", r.get("persona"), r.get("error", ""))

    counts = Counter(f["category"] for f in found)
    lines = ["# Failure taxonomy (generated by scripts/failure_taxonomy.py)", "",
             f"{len(found)} failures of the shipped graph across the result files present ({ambiguous} rows without a persona and a shared id could "
             "not be joined). Dev sets, synthetic jobs.", "",
             "| category | count |", "|---|---|", *[f"| {c} | {n} |" for c, n in counts.most_common()], "",
             "| source | job | gold | predicted | gold reason | category |", "|---|---|---|---|---|---|",
             *[f"| {f['source']} | {f['job_id']} | {f['gold']} | {f['pred']} | {f['reason']} | {f['category']} |" for f in found], "",
             "## Reading", "",
             "Fill in after reading the table: for each category, the cause (rule, retrieval, model, data) and the fix or accepted limit. "
             "A false bid on a scam must be zero; a missed bid costs an opportunity but never money."]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:3 + len(counts) + 3]))
    print(f"wrote {OUT} ({len(found)} failures)")
    if len(found) < 10:
        print("NOTE: fewer than 10 failures in the result files; run `make rdc` / x2 on a larger --sample to reach 10.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
